"""One cached index of installed apps: shell:AppsFolder and the Start-menu shortcuts.

Shared by the app switcher (its launch list, launch_applications.json) and app_identity
(taskbar names). Each scan runs once, lazily, on the shared COM thread; reset() forgets
them so the next call scans again (after apps are installed or removed).
"""

import glob
import os
import threading
from dataclasses import dataclass

from . import shell_com
from .com_thread import on_com_thread

FOLDERID_Desktop = "{B4BFCC3A-DB2C-424C-B029-7FE99A87C641}"
# Generated ids whose shortcut targets say nothing about the app: Visual Studio's
# developer prompts all point at cmd.exe.
GENERATED_ID_PREFIX = "microsoft.autogenerated"


@dataclass
class AppsFolderItem:
    name: str
    # The item's AppUserModelID; for unpackaged apps without one, the shell's
    # "{KNOWNFOLDER}\rest\app.exe" form.
    app_id: str
    # For "{KNOWNFOLDER}\..." ids, the file it stands for; else None.
    path: str | None
    # A shortcut's target (System.Link.TargetParsingPath), if the item is one.
    target: str | None


@dataclass
class Shortcut:
    path: str
    # The file name without .lnk: what the Start menu shows.
    name: str
    target: str | None
    arguments: str
    # The AppUserModelID set on the shortcut, if any.
    app_id: str | None
    in_start_menu: bool


_lock = threading.Lock()
_items: list[AppsFolderItem] | None = None
_shortcuts: list[Shortcut] | None = None
_names_by_path: dict[str, str] | None = None
_ids_by_path: dict[str, str] | None = None


def reset():
    """Forget the scans; the next lookup scans again."""
    global _items, _shortcuts, _names_by_path, _ids_by_path
    with _lock:
        _items = _shortcuts = _names_by_path = _ids_by_path = None


@on_com_thread(timeout=120)
def apps_folder_items() -> list[AppsFolderItem]:
    """Every entry of shell:AppsFolder (Start's "All apps"), scanned once."""
    global _items
    if _items is not None:
        return _items
    items = []
    folders: dict[str, str | None] = {}
    for item in shell_com.iter_folder_items(shell_com.FOLDERID_AppsFolder):
        name = shell_com.item_name(item)
        if not name:
            continue
        parsing = (shell_com.item_name(item, shell_com.SIGDN_DESKTOPABSOLUTEPARSING) or "").replace(shell_com.APPS_FOLDER_PREFIX, "")
        app_id = shell_com.item_property(item, shell_com.PKEY_AppUserModel_ID) or parsing
        path = None
        if app_id.startswith("{") and "}\\" in app_id:
            guid_text, rest = app_id.split("\\", 1)
            if guid_text not in folders:
                folders[guid_text] = shell_com.known_folder_path(guid_text)
            if folders[guid_text]:
                path = os.path.join(folders[guid_text], rest)
        target = None
        if not app_id.startswith("{") and not app_id.lower().startswith(GENERATED_ID_PREFIX):
            target = shell_com.item_string(item, shell_com.PKEY_Link_TargetParsingPath)
        items.append(AppsFolderItem(name, app_id, path, target))
    _items = items
    return items


def _shortcut_roots() -> list[tuple[str, bool]]:
    """Where shortcuts are looked for, in order, and whether each is a Start menu."""
    desktop = shell_com.known_folder_path(FOLDERID_Desktop)
    roots = [(desktop, False)] if desktop else []
    return roots + [
        (os.path.expandvars("%AppData%/Microsoft/Windows/Start Menu/Programs"), True),
        (os.path.expandvars("%ProgramData%/Microsoft/Windows/Start Menu/Programs"), True),
        (os.path.expandvars("%AppData%/Microsoft/Internet Explorer/Quick Launch/User Pinned/TaskBar"), False),
    ]


@on_com_thread(timeout=120)
def shortcuts() -> list[Shortcut]:
    """The .lnk files on the desktop, in the Start menus and pinned to the taskbar, with
    their targets and AppUserModelIDs; scanned once."""
    global _shortcuts
    if _shortcuts is not None:
        return _shortcuts
    found = []
    for root, in_start_menu in _shortcut_roots():
        for path in glob.glob(os.path.join(root, "**/*.lnk"), recursive=True):
            # The shell's property lookups reject the forward slashes glob keeps.
            path = os.path.normpath(path)
            target, arguments = shell_com.shortcut_target(path)
            app_id = shell_com.file_property(path, shell_com.PKEY_AppUserModel_ID) if in_start_menu else None
            found.append(Shortcut(path, os.path.splitext(os.path.basename(path))[0], target, arguments, app_id, in_start_menu))
    _shortcuts = found
    return found


def shortcuts_by_name() -> dict[str, Shortcut]:
    """Shortcut name -> shortcut; later roots win, as community's shortcut_map did."""
    return {s.name: s for s in shortcuts()}


def shortcut_names_by_id() -> dict[str, str]:
    """AppUserModelID (lowercase) -> Start menu shortcut name, for shortcuts that set one:
    how the taskbar names a window whose id has no Apps folder entry of its own, e.g.
    Git Bash's mintty window ("GitForWindows.Bash")."""
    names: dict[str, str] = {}
    # The all-users Start menu first, as before.
    for s in sorted(shortcuts(), key=lambda s: "programdata" not in s.path.lower()):
        if s.in_start_menu and s.app_id:
            names.setdefault(s.app_id.lower(), s.name)
    return names


def names_by_path() -> dict[str, str]:
    """File path (lowercase) -> Start menu name, for unpackaged apps and MMC consoles: a
    running unpinned app's taskbar button uses its Start menu name, e.g. "Command
    Prompt" for cmd.exe rather than its FileDescription."""
    global _names_by_path, _ids_by_path
    if _names_by_path is not None:
        return _names_by_path
    names: dict[str, str] = {}
    ids: dict[str, str] = {}
    # Entries with an AppUserModelID, by their target executable; used only where no
    # entry points at the executable directly ("Windows Media Player Legacy").
    by_target: dict[str, str] = {}
    ids_by_target: dict[str, str] = {}
    for item in apps_folder_items():
        if item.target and item.target.lower().endswith(".exe"):
            by_target.setdefault(item.target.lower(), item.name)
            ids_by_target.setdefault(item.target.lower(), item.app_id)
        # MMC consoles too ("Services" is mmc.exe opening services.msc).
        if item.path and item.path.lower().endswith((".exe", ".msc")):
            names.setdefault(item.path.lower(), item.name)
            ids.setdefault(item.path.lower(), item.app_id)
    for target, name in by_target.items():
        names.setdefault(target, name)
    for target, app_id in ids_by_target.items():
        ids.setdefault(target, app_id)
    with _lock:
        _names_by_path, _ids_by_path = names, ids
    return names


def name_for_path(path: str) -> str | None:
    """The Start menu name for a file: its exact path, else its file name when exactly
    one entry has it. Squirrel apps (GitHub Desktop, Discord, Slack) run from an
    app-<version> folder while their Start menu entry points at the launcher one level
    up."""
    names = names_by_path()
    exact = names.get(path.lower())
    if exact:
        return exact
    file_name = os.path.basename(path).lower()
    matches = {name for target, name in names.items() if os.path.basename(target) == file_name}
    return matches.pop() if len(matches) == 1 else None


def app_id_for_path(path: str) -> str | None:
    """The Apps folder id of an unpackaged app or console by its file, e.g.
    "{1AC14E77-...}\\services.msc": what launch_applications.json is keyed by."""
    names_by_path()
    return (_ids_by_path or {}).get(path.lower())
